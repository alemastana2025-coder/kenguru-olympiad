import random, math


def _opts(correct, ds, seed):
    vals=[]
    for x in [correct]+list(ds):
        s=str(x)
        if s not in vals: vals.append(s)
    k=1
    while len(vals)<5:
        try: s=str(int(correct)+k)
        except: s=f'{correct}-{k}'
        if s not in vals: vals.append(s)
        k+=1
    vals=vals[:5]
    r=random.Random(seed); r.shuffle(vals)
    return vals,str(correct)


def _q(g,i,kk,ru,ans,ds):
    op,correct=_opts(ans,ds,f'KENG-V2-{g}-{i}')
    return {'id':f'g{g}q{i}','grade':g,'points':3 if i<=10 else (4 if i<=20 else 5),'kk':kk,'ru':ru,'options':op,'answer':correct}


