    for g in range(1,12):
        base=[dict(x) for x in existing[g][:10]]
        extra=_low(g) if g<=4 else (_senior(g) if g>=9 else _high(g))
        assert len(extra)==20
        for j,(kk,ru,ans,ds) in enumerate(extra,11): base.append(_q(g,j,kk,ru,ans,ds))
        for i,q in enumerate(base,1):
            q['id']=f'g{g}q{i}'; q['grade']=g; q['points']=3 if i<=10 else (4 if i<=20 else 5)
        out[g]=base
    return out
