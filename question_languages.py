# This original Russian label also needs a Kazakh display translation.
KK_OPTIONS = {'ось Ox': 'Ox осі'}


def localized_options(question, lang):
    labels = RU_OPTIONS if lang == 'ru' else KK_OPTIONS
    return [labels.get(option, option) for option in question['options']]


def answer_is_correct(question, answer, lang):
    if answer is None:
        return False
    # Accept original values from already-open tests as well as localized labels.
    if answer == question['answer']:
        return True
    correct_index = question['options'].index(question['answer'])
    return answer == localized_options(question, lang)[correct_index]
